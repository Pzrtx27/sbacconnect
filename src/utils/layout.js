/* ความกว้างของ "เปลือกแอป" (header + เนื้อหา) แยกตามบทบาท

   แอปนี้เขียนแบบ mobile-first และคนส่วนใหญ่ก็ใช้บนมือถือจริง ๆ
   แต่ทุกบทบาทมีคนเปิดบนคอมอยู่แล้ว ทั้งนักเรียนที่ห้องคอม ครูที่โต๊ะพัก
   ฝ่ายวิชาการที่กรอกข้อมูล และบาริสต้าที่จอเคาน์เตอร์
   ปล่อยให้เป็นคอลัมน์ 448px กลางจอ 1920px คือทิ้งพื้นที่ไป 75% เปล่า ๆ

   ต่ำกว่า xl (1280px) ทุกบทบาทยังเป็นคอลัมน์มือถือเหมือนเดิม
   เพราะแท็บเล็ตกับโน้ตบุ๊กจอเล็กอ่านคอลัมน์เดียวสบายกว่าอยู่แล้ว

   ค่าที่ต่างกันคือ "กว้างได้แค่ไหน" ไม่ใช่ "กว้างหรือไม่":
     academic  กว้างสุด เพราะมีตารางพรีวิวรายชื่อนักเรียนที่ยิ่งกว้างยิ่งอ่านง่าย
     ที่เหลือ  1200px พอ กว้างกว่านี้การ์ดจะยืดจนอ่านลำบาก

   หน้าบาริสต้าไม่ได้ผ่านเปลือกนี้ มัน layout เต็มจอของตัวเองใน App.jsx */

const SHELL_WIDTH = {
  academic: 'max-w-md xl:max-w-[1400px]',
  student: 'max-w-md xl:max-w-[1200px]',
  teacher: 'max-w-md xl:max-w-[1200px]',
};

/** คลาสความกว้างของเปลือกแอปสำหรับบทบาทนั้น ๆ
 *  ใช้ร่วมกันระหว่าง <main> กับ <Header> เพื่อให้ขอบซ้าย-ขวาตรงกันเสมอ */
export function shellWidthClass(role) {
  return SHELL_WIDTH[String(role || '').toLowerCase().trim()] || 'max-w-md';
}

/* ความกว้างของ "หน้าที่เป็นคอลัมน์เดียว" — ตารางสอน คำสั่งซื้อ ประวัติ หน้าแรกของครู
   หน้าพวกนี้เป็นรายการเรียงลงมาแถวเดียว ยืดเต็ม 1200px แล้วตาต้องกวาดไกลเกินไป
   จึงคุมให้แคบกว่าเปลือกอีกชั้น

   ที่ต้องมีค่าคงที่ตัวนี้ เพราะเดิมแต่ละหน้าเลือกเองคนละค่า (4xl บ้าง 3xl บ้าง ไม่ใส่บ้าง)
   นักเรียนกดจากหน้าหลัก -> ตารางสอน -> คำสั่งซื้อ แล้วเนื้อหาขยับกว้าง-แคบทุกครั้งที่เปลี่ยนหน้า

   หน้าที่จงใจใช้เต็มความกว้างจะไม่ใส่ค่านี้ ได้แก่ หน้าแรกนักเรียน (สองคอลัมน์ มีรางปฏิทิน)
   หน้าสั่งกาแฟ (ตารางเมนู) และหน้าฝ่ายวิชาการ (ตารางรายชื่อยิ่งกว้างยิ่งอ่านง่าย) */
export const READING_WIDTH = 'xl:max-w-4xl';
